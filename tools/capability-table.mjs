#!/usr/bin/env node
// The capability table of README.md (Round 24, B6), generated from docs/capabilities.md:
// each job (a "## " section with a "*In <modules>; since <version>.*" line) becomes a row:
// job, module, example (a link to its section), since. `--check` exits 1 when README.md
// is not up to date (the docs test runs it).
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const caps = readFileSync(new URL('docs/capabilities.md', root), 'utf8');
const anchor = (h) => h.toLowerCase().replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '-');
const rows = [];
for (const m of caps.matchAll(/^## (.+)\n\n\*In (.+); since (0\.\d+)\.\*/gm)) rows.push(`| ${m[1]} | ${m[2]} | [example](docs/capabilities.md#${anchor(m[1])}) | ${m[3]} |`);
const table = ['<!-- capabilities: generated by tools/capability-table.mjs from docs/capabilities.md -->', '| Job | In | Example | Since |', '| --- | --- | --- | --- |', ...rows, '<!-- /capabilities -->'].join('\n');
const readme = readFileSync(new URL('README.md', root), 'utf8');
const re = /<!-- capabilities:[\s\S]*?<!-- \/capabilities -->/;
const next = re.test(readme) ? readme.replace(re, table) : readme.replace(/\n## /, `\n## What it can do\n\n${table}\n\n## `);
if (process.argv.includes('--check')) { if (next !== readme) { console.error('README.md capability table is not up to date: node tools/capability-table.mjs'); process.exit(1); } console.log(`README.md: ${rows.length} jobs, up to date`); }
else { writeFileSync(new URL('README.md', root), next); console.log(`README.md: ${rows.length} jobs`); }
