#!/usr/bin/env node
// Vendors Z3 for the browser provider (browser/smt-z3.mjs) into docs/vendor/z3-solver-<version>/, the
// library's site. A development step, run when the Z3 version changes; nothing here is a dependency.
//
//   Z3_SOLVER=<path to an installed z3-solver package> ESBUILD=<path to an esbuild binary> node tools/vendor-z3.mjs
//
// Z3_SOLVER defaults to experiments/node_modules/z3-solver, ESBUILD to `esbuild` on PATH. It writes
//   z3-built.js        Emscripten loader, unchanged (also the pthread worker script)
//   z3-built.wasm.gz   the WebAssembly module, gzip -9 (the browser inflates it with DecompressionStream)
//   z3-api.mjs         build/browser.js (the high- and low-level API) bundled as one ES module by esbuild
//   LICENSE, README.md
// The directory is named by the version, so a published URL never changes content and caches keep it.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { gzipSync, constants } from 'node:zlib';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = resolve(process.env.Z3_SOLVER ?? resolve(root, 'experiments/node_modules/z3-solver'));
const esbuild = process.env.ESBUILD ?? 'esbuild';
const pkg = JSON.parse(readFileSync(resolve(pkgDir, 'package.json'), 'utf8'));
const expected = /export const z3Version = '([^']+)'/.exec(readFileSync(resolve(root, 'browser/smt-z3.mjs'), 'utf8'))[1];
if (pkg.name !== 'z3-solver' || pkg.version !== expected) throw Error(`vendor-z3: ${pkgDir} is ${pkg.name}@${pkg.version}; browser/smt-z3.mjs expects z3-solver@${expected}`);
const esbuildVersion = execFileSync(esbuild, ['--version'], { encoding: 'utf8' }).trim();
const out = resolve(root, `docs/vendor/z3-solver-${pkg.version}`);
mkdirSync(out, { recursive: true });

const build = resolve(pkgDir, 'build');
copyFileSync(resolve(build, 'z3-built.js'), resolve(out, 'z3-built.js'));
const wasm = readFileSync(resolve(build, 'z3-built.wasm'));
writeFileSync(resolve(out, 'z3-built.wasm.gz'), gzipSync(wasm, { level: constants.Z_BEST_COMPRESSION }));
const api = execFileSync(esbuild, [resolve(build, 'browser.js'), '--bundle', '--format=esm', '--platform=browser', '--define:global=globalThis',
  '--minify', '--legal-comments=none', '--log-level=warning'], { encoding: 'utf8', maxBuffer: 64 << 20 });
writeFileSync(resolve(out, 'z3-api.mjs'), `// z3-solver ${pkg.version}: build/browser.js (the high- and low-level JavaScript API) bundled as one ES module
// by esbuild ${esbuildVersion} (tools/vendor-z3.mjs). Source: https://www.npmjs.com/package/z3-solver,
// https://github.com/Z3Prover/z3/tree/master/src/api/js. License: MIT (Microsoft Corporation); includes
// async-mutex (MIT) and tslib (0BSD). Generated; do not edit.
${api}`);
const license = ['LICENSE.txt', 'LICENSE'].map((f) => resolve(pkgDir, f)).find(existsSync);
copyFileSync(license, resolve(out, 'LICENSE'));

const sha = (file) => createHash('sha256').update(readFileSync(resolve(out, file))).digest('hex');
const size = (file) => readFileSync(resolve(out, file)).length;
const files = ['z3-built.js', 'z3-built.wasm.gz', 'z3-api.mjs'];
writeFileSync(resolve(out, 'README.md'), `# z3-solver ${pkg.version} for the browser

Loaded on demand by \`../../smt-z3.mjs\` (source: \`browser/smt-z3.mjs\`), the browser provider for
\`std.problem\`. Not part of the library bundle and never loaded until a problem needs it. Generated by
\`tools/vendor-z3.mjs\` from the npm package z3-solver ${pkg.version} with esbuild ${esbuildVersion}. License: MIT
(Microsoft Corporation, see LICENSE); z3-api.mjs also contains async-mutex (MIT) and tslib (0BSD).

z3-built.wasm (${wasm.length} bytes, sha256 ${createHash('sha256').update(wasm).digest('hex')}) is stored
gzipped; the provider inflates it with the browser's DecompressionStream. Z3 runs its solver in pthreads,
so the page must be cross-origin isolated (SharedArrayBuffer).

| File | Bytes | sha256 |
| --- | --- | --- |
${files.map((f) => `| ${f} | ${size(f)} | ${sha(f)} |`).join('\n')}
`);
console.log(`vendored z3-solver ${pkg.version} into ${out} with esbuild ${esbuildVersion}`);
for (const f of files) console.log(`  ${f.padEnd(18)} ${size(f)} bytes`);
